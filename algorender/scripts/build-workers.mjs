// Bundles the JavaScript runner's worker (src/workspace/js/js.worker.ts and
// everything it imports) into one self-contained classic script,
// public/workers/js.js, beside the Python worker. Learner code runs in workers
// inside a sandboxed, opaque-origin iframe (public/sandbox.html), which starts
// them from their text: it can't follow imports back to the app's origin, and
// a module worker can't start from text there.
//
// Runs before `dev` and `build`; `npm run workers -- --watch` rebuilds on change.

import { build, context } from 'esbuild';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');

/** @type {import('esbuild').BuildOptions} */
const options = {
  entryPoints: [path.join(root, 'src/workspace/js/js.worker.ts')],
  outfile: path.join(root, 'public/workers/js.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2023',
  minify: true,
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build-workers.mjs from src/workspace/js/js.worker.ts; edit that, not this.' },
  logLevel: 'info',
};

if (process.argv.includes('--watch')) {
  const ctx = await context(options);
  await ctx.watch();
} else {
  await build(options);
}
